  /// Default expense category slug -> localized display name.
  String categoryName(String slug) {
    final map = lang == 'fr'
        ? _catFr
        : lang == 'ar'
            ? _catAr
            : _catEn;
    // Custom/renamed categories store a slugged readable name; render it with
    // capitalization and spaces instead of raw underscores.
    if (map[slug] case final localized?) return localized;
    return slug
        .split('_')
        .where((s) => s.isNotEmpty)
        .map((s) => '${s[0].toUpperCase()}${s.substring(1)}')
        .join(' ');
  }

